    /// <summary>
    /// Профиль миссии из её условий (GDD §7.2): из него таблица берёт колонку «Цель», а подсказка — тип схемы
    /// траектории. Ручной разметки нет — новая миссия получает осмысленную картинку сама.
    /// </summary>
    public sealed class MissionProfile
    {
        /// <summary>Тело-цель, кроме Земли (null — миссия у Земли).</summary>
        public string Target;
        public bool Suborbital, EarthOrbit, Dock, Return;
        public bool TargetSoi, Impact, Flyby, FarSide, TargetOrbit, Landing, Ascent, Drive;
        /// <summary>Спуск на воду: старт с Канаверала — американские капсулы садились в океан.</summary>
        public bool Splashdown;
        /// <summary>Посадка на ВПП (крылатые «Шаттл», «Буран»): без парашюта, а Канаверал не значит океан.</summary>
        public bool Runway;
        public string StationName;

        public static MissionProfile Of(MissionDef d)
        {
            var p = new MissionProfile { Splashdown = d.SiteId == "canaveral" || d.SiteId == "starbase", StationName = d.StationName };
            bool landed = false;
            foreach (var o in d.Objectives)
            {
                bool earth = o.Body == "earth";
                if (!earth && p.Target == null) p.Target = o.Body;
                switch (o.Type)
                {
                    case ObjectiveType.Altitude: if (earth) p.Suborbital = true; break;
                    case ObjectiveType.Orbit:
                        if (earth) p.EarthOrbit = true;
                        else { p.TargetOrbit = true; if (landed) p.Ascent = true; }
                        break;
                    case ObjectiveType.EnterSoi: p.TargetSoi = true; break;
                    case ObjectiveType.Flyby: p.Flyby = true; break;
                    case ObjectiveType.FarSidePhoto: p.FarSide = true; break;
                    case ObjectiveType.Impact: p.Impact = true; break;
                    case ObjectiveType.Landing: p.Landing = true; landed = true; break;
                    case ObjectiveType.Drive: p.Drive = true; break;
                    case ObjectiveType.Dock: p.Dock = true; break;
                    case ObjectiveType.Return: p.Return = true; break;
                    case ObjectiveType.Runway: p.Return = true; p.Runway = true; break;
                }
            }
            // Посадка с окололунной орбиты (MissionDef.LunarOrbit) — на схеме сначала виток, потом спуск.
            if (d.LunarOrbit > 0) p.TargetOrbit = true;
            if (p.Runway) p.Splashdown = false;
            return p;
        }

        /// <summary>Имя тела без загруженной системы (тесты, конструктор): совпадает с SolarSystem для частых целей.</summary>
        static string FallbackName(string id)
        {
            switch (id)
            {
                case "moon": return "Луна";
                case "mars": return "Марс";
                case "venus": return "Венера";
                default: return id;
            }
        }

        /// <summary>Короткая цель для таблицы: «Орбита и спуск», «Посадка: Луна + луноход», «Стыковка: МКС».</summary>
        public string Goal(SolarSystem sys)
        {
            string b = Target == null ? null : (sys?.Get(Target)?.Name ?? FallbackName(Target));
            string ret = Return ? " и возврат" : "";
            if (Dock) return "Стыковка: " + (StationName ?? "станция") + ret;
            if (Target != null)
            {
                if (Drive) return $"Посадка: {b} + луноход";
                if (Landing && Ascent) return $"Высадка: {b}" + ret;
                if (Landing) return $"Мягкая посадка: {b}";
                if (TargetOrbit) return $"Орбита: {b}" + ret;
                if (Impact) return $"Попадание: {b}";
                if (FarSide || Flyby) return $"Облёт: {b}";
                if (TargetSoi) return $"Сфера влияния: {b}";
                return b;
            }
            if (EarthOrbit && Runway) return "Орбита и посадка на ВПП";
            if (EarthOrbit) return Return ? "Орбита и спуск" : "Орбита Земли";
            if (Suborbital) return "Суборбитальный";
            return "—";
        }
    }
